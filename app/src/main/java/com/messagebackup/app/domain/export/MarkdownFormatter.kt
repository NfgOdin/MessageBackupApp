package com.messagebackup.app.domain.export

import com.messagebackup.app.model.ConversationThread
import com.messagebackup.app.model.MessageDirection
import com.messagebackup.app.model.MessageItem
import java.time.Instant
import java.time.ZoneId
import java.time.format.DateTimeFormatter

/**
 * Generates formatted Markdown (.md) documents from conversation threads and messages.
 * Supports pagination headers, timestamps, sender quotes, and relative inline media links.
 */
class MarkdownFormatter {

    private val dateFormatter = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss")
        .withZone(ZoneId.systemDefault())

    /**
     * Formats a conversation part into structured Markdown.
     *
     * @param thread The conversation thread metadata.
     * @param messages Chronological list of SMS and MMS messages for this part.
     * @param currentPart Index of current part (1-based, 1 is oldest).
     * @param totalParts Total number of parts produced.
     * @param prevFileName Relative filename of previous part.
     * @param nextFileName Relative filename of next part.
     * @param mediaSubdir Relative folder path where media attachments are stored.
     * @return Formatted Markdown string.
     */
    fun formatConversationPart(
        thread: ConversationThread,
        messages: List<MessageItem>,
        currentPart: Int = 1,
        totalParts: Int = 1,
        prevFileName: String? = null,
        nextFileName: String? = null,
        mediaSubdir: String = "media/"
    ): String {
        val sb = StringBuilder()

        // Document Header
        sb.append("# Conversation with ${thread.displayName}\n\n")
        if (totalParts > 1) {
            sb.append("**Part $currentPart of $totalParts**\n\n")
        }
        sb.append("- **Address:** `${thread.address}`\n")
        if (!thread.contactName.isNullOrBlank()) {
            sb.append("- **Contact Name:** ${thread.contactName}\n")
        }
        sb.append("- **Messages in this part:** ${messages.size}\n")
        sb.append("- **Export Date:** ${dateFormatter.format(Instant.now())}\n\n")

        // Top Navigation links if paginated
        if (totalParts > 1) {
            sb.append(renderNavLinks(currentPart, totalParts, prevFileName, nextFileName))
            sb.append("\n\n")
        }

        sb.append("---\n\n")

        if (messages.isEmpty()) {
            sb.append("*No messages found in this segment.*\n")
            return sb.toString()
        }

        // Messages List
        for (msg in messages) {
            val formattedTime = dateFormatter.format(Instant.ofEpochMilli(msg.timestamp))
            val isOutgoing = (msg.direction == MessageDirection.OUTGOING)
            val senderLabel = if (isOutgoing) "**Me**" else "**${msg.sender}**"

            sb.append("> $senderLabel *($formattedTime)*:\n")

            if (msg.body.isNotBlank()) {
                val lines = msg.body.lines()
                for (line in lines) {
                    sb.append("> $line\n")
                }
            }

            // Inline MMS media attachments
            for (attachment in msg.attachments) {
                val relativePath = "$mediaSubdir${attachment.fileName}"
                if (attachment.contentType.startsWith("image/")) {
                    sb.append(">\n")
                    sb.append("> ![${attachment.fileName}]($relativePath)\n")
                } else if (attachment.contentType.startsWith("audio/")) {
                    sb.append(">\n")
                    sb.append("> [Audio: ${attachment.fileName}]($relativePath)\n")
                } else {
                    sb.append(">\n")
                    sb.append("> [Attachment: ${attachment.fileName}]($relativePath)\n")
                }
            }

            sb.append("\n\n")
        }

        sb.append("---\n")

        // Bottom Navigation links if paginated
        if (totalParts > 1) {
            sb.append(renderNavLinks(currentPart, totalParts, prevFileName, nextFileName))
            sb.append("\n\n")
        }

        sb.append("*Generated by Message Backup & Export*\n")
        return sb.toString()
    }

    private fun renderNavLinks(
        currentPart: Int,
        totalParts: Int,
        prevFileName: String?,
        nextFileName: String?
    ): String {
        val prev = if (prevFileName != null) "[← Previous Part]($prevFileName)" else "*(First Part)*"
        val next = if (nextFileName != null) "[Next Part →]($nextFileName)" else "*(Latest Part)*"
        return "**$prev** | **Part $currentPart of $totalParts** | **$next**"
    }
}
